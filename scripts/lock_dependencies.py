#!/usr/bin/env python3
"""Resolve frozen versions to official CPython 3.10/Linux amd64 artifact hashes.

Development tool only; needs packaging. Normal builds consume the committed locks.
Use HTTPS_PROXY/HTTP_PROXY normally; --direct bypasses a broken local proxy.
"""
from __future__ import annotations
import argparse
import concurrent.futures
import hashlib
import html
import json
from pathlib import Path
import re
import urllib.parse
import urllib.request
from packaging.tags import compatible_tags, cpython_tags
from packaging.utils import parse_wheel_filename

ROOT = Path(__file__).resolve().parents[1]
FLASH_URL = ('https://github.com/Dao-AILab/flash-attention/releases/download/v2.8.3/'
             'flash_attn-2.8.3+cu12torch2.8cxx11abiTRUE-cp310-cp310-linux_x86_64.whl')
FLASH_SHA = '75c51f34bb93c5a4438d6b767547ca6c22a9bfc6b29b5646dda98e943cd75d99'
PLATFORMS = [f'manylinux_2_{n}_x86_64' for n in range(36, 4, -1)] + [
    'manylinux2014_x86_64', 'manylinux2010_x86_64', 'manylinux1_x86_64', 'linux_x86_64']
TAGS = list(cpython_tags((3, 10), ['cp310'], PLATFORMS)) + list(
    compatible_tags((3, 10), 'cp310', PLATFORMS))
RANK = {tag: n for n, tag in enumerate(TAGS)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--direct', action='store_true')
    args = parser.parse_args()
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({})) if args.direct else urllib.request.build_opener()

    def read(url):
        with opener.open(urllib.request.Request(url, headers={'User-Agent': 'ditserve-lock/1'}), timeout=90) as response:
            return response.read()

    def rank(filename):
        try:
            return min((RANK[t] for t in parse_wheel_filename(filename)[3] if t in RANK), default=10**9)
        except ValueError:
            return 10**9

    def resolve(pair):
        name, version = pair
        if name == 'flash-attn':
            return {'name': name, 'version': version, 'url': FLASH_URL, 'sha256': FLASH_SHA,
                    'filename': FLASH_URL.rsplit('/', 1)[1], 'bytes': 256026321, 'origin': 'official GitHub release'}
        if name in {'torch', 'torchvision'}:
            page = read(f'https://download.pytorch.org/whl/cu126/{name}/').decode()
            candidates = []
            for url in re.findall(r'href="([^"]+)"', page):
                url = html.unescape(url)
                filename = urllib.parse.unquote(urllib.parse.urlsplit(url).path.rsplit('/', 1)[-1])
                try:
                    _, v, _, _ = parse_wheel_filename(filename)
                    if str(v) == version and rank(filename) < 10**9:
                        candidates.append((rank(filename), filename, url))
                except ValueError:
                    continue
            if not candidates:
                raise RuntimeError(f'No compatible official torch artifact: {pair}')
            _, filename, url = min(candidates)
            checksum = urllib.parse.parse_qs(urllib.parse.urlsplit(url).fragment).get('sha256', [None])[0]
            if not checksum:
                raise RuntimeError(f'Official index omits hash: {url}')
            with opener.open(urllib.request.Request(url.split('#')[0], method='HEAD'), timeout=90) as response:
                size = int(response.headers['Content-Length'])
            return {'name': name, 'version': version, 'filename': filename, 'bytes': size,
                    'url': url.split('#')[0], 'sha256': checksum, 'origin': 'official PyTorch index'}
        data = json.loads(read(f'https://pypi.org/pypi/{name}/{version}/json'))
        wheels = sorted((rank(f['filename']), f['filename'], f) for f in data['urls']
                        if not f.get('yanked') and rank(f['filename']) < 10**9)
        if wheels:
            item = wheels[0][2]
        elif name == 'antlr4-python3-runtime':
            item = next(f for f in data['urls'] if f['packagetype'] == 'sdist' and not f.get('yanked'))
        else:
            raise RuntimeError(f'No compatible wheel on PyPI: {pair}')
        return {'name': name, 'version': version, 'filename': item['filename'], 'url': item['url'],
                'sha256': item['digests']['sha256'], 'bytes': item['size'], 'origin': 'official PyPI'}

    versions = json.loads((ROOT / 'configs/dependency-versions.json').read_text())
    pairs = sorted({(name, version) for group in ['runtime', 'longlive'] for name, version in versions[group].items()})
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        artifacts = dict(zip(pairs, pool.map(resolve, pairs)))
    for group in ['runtime', 'longlive']:
        entries = [artifacts[pair] for pair in sorted(versions[group].items())]
        lock = ['# Generated by scripts/lock_dependencies.py; CPython 3.10, Debian bookworm, linux/amd64.',
                '# Exact upstream artifacts: no index resolution, no unpinned transitive dependencies.',
                '# antlr4 is the sole sdist; build with the separately pinned setuptools/wheel and --no-build-isolation.',
                '--require-hashes']
        lock += [f"{e['name']} @ {e['url']} \\\n    --hash=sha256:{e['sha256']}" for e in entries]
        (ROOT / f'configs/requirements-{group}.lock').write_text('\n'.join(lock) + '\n')
        (ROOT / f'configs/artifacts-{group}.json').write_text(json.dumps({'schema_version': 1, 'artifacts': entries}, indent=2) + '\n')
        print(f'{group}: {len(entries)} artifacts')


if __name__ == '__main__':
    main()
